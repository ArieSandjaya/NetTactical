using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;

namespace TacticalRmm.Infrastructure.Persistence;

/// <summary>
/// EnsureCreated only builds a database that does not exist yet; it never adds tables or columns to an existing one.
/// These idempotent statements bring a database created by an earlier version up to date (each is safe to run on every start).
/// Add new statements at the end when an entity or column is added; a fresh database already has them from EnsureCreated.
/// </summary>
public static class SchemaUpgrade
{
    private static readonly string[] Steps =
    [
        // v2: WMI detail written by the agent / nats-api
        "ALTER TABLE agents_agent ADD COLUMN IF NOT EXISTS wmi_detail jsonb",
        // v3: VNC passwords
        """
        CREATE TABLE IF NOT EXISTS vnc_credentials (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            label character varying(100) NOT NULL,
            priority integer NOT NULL,
            enabled boolean NOT NULL,
            secret text NOT NULL,
            created_on timestamp with time zone NOT NULL,
            created_by text NULL)
        """,
        "CREATE INDEX IF NOT EXISTS ix_vnc_credentials_priority ON vnc_credentials (priority)",
        // v4: alert notification channels (email / webhook)
        """
        CREATE TABLE IF NOT EXISTS notification_channels (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name character varying(100) NOT NULL,
            kind character varying(20) NOT NULL,
            enabled boolean NOT NULL,
            min_severity text NOT NULL,
            notify_resolved boolean NOT NULL,
            only_flagged boolean NOT NULL,
            host text NULL,
            port integer NOT NULL,
            start_tls boolean NOT NULL,
            username text NULL,
            from_address text NULL,
            recipients text NULL,
            url text NULL,
            format text NULL,
            secret text NULL,
            last_attempt timestamp with time zone NULL,
            last_ok boolean NULL,
            last_error character varying(400) NULL,
            created_on timestamp with time zone NOT NULL,
            created_by text NULL)
        """,
        "CREATE UNIQUE INDEX IF NOT EXISTS ix_notification_channels_name ON notification_channels (name)",
    ];

    public static async Task RunAsync(AppDbContext db, ILogger log, CancellationToken ct = default)
    {
        foreach (var sql in Steps)
        {
            try { await db.Database.ExecuteSqlRawAsync(sql, ct); }
            catch (Exception e) { log.LogError(e, "schema upgrade step failed: {Sql}", sql.Length > 120 ? sql[..120] : sql); throw; }
        }
    }
}
