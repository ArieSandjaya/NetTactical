using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;

namespace TacticalRmm.Infrastructure.Persistence;

/// <summary>
/// EnsureCreated only builds a database that does not exist yet; it never adds tables or columns to an existing one.
/// These idempotent statements bring a database created by an earlier version up to date (each is safe to run on every start).
/// Add new statements at the end when an entity or column is added; a fresh database already has them from EnsureCreated.
/// </summary>
public static class SchemaUpgrade
{
    private static readonly string[] Steps =
    [
        // v2: WMI detail written by the agent / nats-api
        "ALTER TABLE agents_agent ADD COLUMN IF NOT EXISTS wmi_detail jsonb",
        // v3: VNC passwords
        """
        CREATE TABLE IF NOT EXISTS vnc_credentials (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            label character varying(100) NOT NULL,
            priority integer NOT NULL,
            enabled boolean NOT NULL,
            secret text NOT NULL,
            created_on timestamp with time zone NOT NULL,
            created_by text NULL)
        """,
        "CREATE INDEX IF NOT EXISTS ix_vnc_credentials_priority ON vnc_credentials (priority)",
        // v4: alert notification channels (email / webhook)
        """
        CREATE TABLE IF NOT EXISTS notification_channels (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name character varying(100) NOT NULL,
            kind character varying(20) NOT NULL,
            enabled boolean NOT NULL,
            min_severity text NOT NULL,
            notify_resolved boolean NOT NULL,
            only_flagged boolean NOT NULL,
            host text NULL,
            port integer NOT NULL,
            start_tls boolean NOT NULL,
            username text NULL,
            from_address text NULL,
            recipients text NULL,
            url text NULL,
            format text NULL,
            secret text NULL,
            last_attempt timestamp with time zone NULL,
            last_ok boolean NULL,
            last_error character varying(400) NULL,
            created_on timestamp with time zone NOT NULL,
            created_by text NULL)
        """,
        "CREATE UNIQUE INDEX IF NOT EXISTS ix_notification_channels_name ON notification_channels (name)",
            // v5: Windows Update approval and schedule (columns of the patch policy)
        "ALTER TABLE win_update_policies ADD COLUMN IF NOT EXISTS critical text NOT NULL DEFAULT 'inherit'",
        "ALTER TABLE win_update_policies ADD COLUMN IF NOT EXISTS important text NOT NULL DEFAULT 'inherit'",
        "ALTER TABLE win_update_policies ADD COLUMN IF NOT EXISTS moderate text NOT NULL DEFAULT 'inherit'",
        "ALTER TABLE win_update_policies ADD COLUMN IF NOT EXISTS low text NOT NULL DEFAULT 'inherit'",
        "ALTER TABLE win_update_policies ADD COLUMN IF NOT EXISTS other text NOT NULL DEFAULT 'inherit'",
        "ALTER TABLE win_update_policies ADD COLUMN IF NOT EXISTS run_time_frequency text NOT NULL DEFAULT 'inherit'",
        "ALTER TABLE win_update_policies ADD COLUMN IF NOT EXISTS run_time_hour integer NOT NULL DEFAULT 3",
        "ALTER TABLE win_update_policies ADD COLUMN IF NOT EXISTS run_time_weekdays integer NOT NULL DEFAULT 0",
        "ALTER TABLE win_update_policies ADD COLUMN IF NOT EXISTS run_time_day integer NOT NULL DEFAULT 1",
        "ALTER TABLE win_update_policies ADD COLUMN IF NOT EXISTS last_run_at timestamp with time zone NULL",
        // v6: policy assigned to a client or a site (agent > site > client)
        "ALTER TABLE clients ADD COLUMN IF NOT EXISTS policy_id integer NULL REFERENCES policies (id) ON DELETE SET NULL",
        "ALTER TABLE sites ADD COLUMN IF NOT EXISTS policy_id integer NULL REFERENCES policies (id) ON DELETE SET NULL",
        "CREATE INDEX IF NOT EXISTS ix_clients_policy_id ON clients (policy_id)",
        "CREATE INDEX IF NOT EXISTS ix_sites_policy_id ON sites (policy_id)",
        // v7: alert templates, assignable to a client or a site
        """
        CREATE TABLE IF NOT EXISTS alert_templates (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name character varying(100) NOT NULL,
            enabled boolean NOT NULL,
            is_default boolean NOT NULL,
            flag_agent_overdue boolean NOT NULL,
            flag_check_failures boolean NOT NULL,
            flag_task_failures boolean NOT NULL,
            created_by text NULL,
            created_time timestamp with time zone NULL,
            modified_by text NULL,
            modified_time timestamp with time zone NULL)
        """,
        "CREATE UNIQUE INDEX IF NOT EXISTS ix_alert_templates_name ON alert_templates (name)",
        "ALTER TABLE clients ADD COLUMN IF NOT EXISTS alert_template_id integer NULL REFERENCES alert_templates (id) ON DELETE SET NULL",
        "ALTER TABLE sites ADD COLUMN IF NOT EXISTS alert_template_id integer NULL REFERENCES alert_templates (id) ON DELETE SET NULL",
        "CREATE INDEX IF NOT EXISTS ix_clients_alert_template_id ON clients (alert_template_id)",
        "CREATE INDEX IF NOT EXISTS ix_sites_alert_template_id ON sites (alert_template_id)",
        // v8: custom fields (definitions and values)
        """
        CREATE TABLE IF NOT EXISTS custom_fields (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name character varying(100) NOT NULL,
            model character varying(10) NOT NULL,
            type character varying(20) NOT NULL,
            options text NULL,
            default_value text NULL,
            created_by text NULL,
            created_time timestamp with time zone NULL)
        """,
        "CREATE UNIQUE INDEX IF NOT EXISTS ix_custom_fields_model_name ON custom_fields (model, name)",
        """
        CREATE TABLE IF NOT EXISTS custom_field_values (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            field_id integer NOT NULL REFERENCES custom_fields (id) ON DELETE CASCADE,
            target_id integer NOT NULL,
            value text NOT NULL)
        """,
        "CREATE UNIQUE INDEX IF NOT EXISTS ix_custom_field_values_field_id_target_id ON custom_field_values (field_id, target_id)",
        // v9: script snippets
        """
        CREATE TABLE IF NOT EXISTS script_snippets (
            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name character varying(64) NOT NULL,
            description text NULL,
            code text NOT NULL,
            created_by text NULL,
            created_time timestamp with time zone NULL,
            modified_by text NULL,
            modified_time timestamp with time zone NULL)
        """,
        "CREATE UNIQUE INDEX IF NOT EXISTS ix_script_snippets_name ON script_snippets (name)",
        // v10: when an agent's installed-software list was received
        "ALTER TABLE installed_software ADD COLUMN IF NOT EXISTS updated_at timestamp with time zone NULL",
        // v11: finer permissions (as in Tactical RMM's Role). Existing roles get the new permission once, from the permission that used to cover the feature,
        // so nobody loses access on upgrade. The marker makes this run only once: a permission an admin removes later stays removed.
        "CREATE TABLE IF NOT EXISTS schema_marks (name text PRIMARY KEY)",
        """
        DO $$ BEGIN
          IF NOT EXISTS (SELECT 1 FROM schema_marks WHERE name = 'perms_v11') THEN
            UPDATE roles SET permissions = permissions || ARRAY['can_manage_procs','can_use_mesh','can_manage_software']::text[] WHERE 'can_send_cmd' = ANY(permissions);
            UPDATE roles SET permissions = permissions || ARRAY['can_update_agents']::text[] WHERE 'can_manage_agents' = ANY(permissions);
            UPDATE roles SET permissions = permissions || ARRAY['can_run_bulk']::text[] WHERE permissions && ARRAY['can_send_cmd','can_run_scripts','can_reboot_agents','can_edit_agent']::text[];
            UPDATE roles SET permissions = permissions || ARRAY['can_list_notes']::text[] WHERE 'can_list_agents' = ANY(permissions);
            UPDATE roles SET permissions = permissions || ARRAY['can_manage_notes']::text[] WHERE 'can_edit_agent' = ANY(permissions);
            UPDATE roles SET permissions = COALESCE((SELECT array_agg(DISTINCT p) FROM unnest(permissions) AS p), ARRAY[]::text[]);
            INSERT INTO schema_marks (name) VALUES ('perms_v11');
          END IF;
        END $$
        """,
        // v12: the same, once, for event logs, URL actions and deployments. Server maintenance and core settings start as administrator-only (new features).
        """
        DO $$ BEGIN
          IF NOT EXISTS (SELECT 1 FROM schema_marks WHERE name = 'perms_v12') THEN
            UPDATE roles SET permissions = permissions || ARRAY['can_view_eventlogs']::text[] WHERE 'can_send_cmd' = ANY(permissions);
            UPDATE roles SET permissions = permissions || ARRAY['can_run_urlactions']::text[] WHERE 'can_list_agents' = ANY(permissions);
            UPDATE roles SET permissions = permissions || ARRAY['can_list_deployments','can_manage_deployments']::text[] WHERE 'can_install_agents' = ANY(permissions);
            UPDATE roles SET permissions = COALESCE((SELECT array_agg(DISTINCT p) FROM unnest(permissions) AS p), ARRAY[]::text[]);
            INSERT INTO schema_marks (name) VALUES ('perms_v12');
          END IF;
        END $$
        """,
];

    public static async Task RunAsync(AppDbContext db, ILogger log, CancellationToken ct = default)
    {
        foreach (var sql in Steps)
        {
            try { await db.Database.ExecuteSqlRawAsync(sql, ct); }
            catch (Exception e) { log.LogError(e, "schema upgrade step failed: {Sql}", sql.Length > 120 ? sql[..120] : sql); throw; }
        }
    }
}
