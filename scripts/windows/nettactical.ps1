<#
 NetTactical helper for Windows (Docker Desktop).
 Usage (from the repository folder):   .\scripts\windows\nettactical.cmd <command>
   setup      create .env with generated secrets (first time only)
   up         build and start PostgreSQL, NATS and the API
   down       stop everything (data is kept)
   status     show containers and check that the ports answer
   logs       follow logs, optionally for one service: logs api | nats | db
   update     git pull (if this is a git checkout), then rebuild and restart
   firewall   open the API and NATS ports in Windows Firewall (run as Administrator)
   backup     dump the database to .\backups
#>
param(
    [Parameter(Position = 0)][ValidateSet('setup', 'up', 'down', 'status', 'logs', 'update', 'firewall', 'backup', 'help')][string]$Command = 'help',
    [Parameter(Position = 1)][string]$Arg = '',
    [string]$PublicUrl = ''
)
$ErrorActionPreference = 'Stop'
$Root = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
Set-Location $Root
$EnvFile = Join-Path $Root '.env'

function Fail($msg) { Write-Host "ERROR: $msg" -ForegroundColor Red; exit 1 }
function Info($msg) { Write-Host $msg -ForegroundColor Cyan }

function Test-Docker {
    if (-not (Get-Command docker -ErrorAction SilentlyContinue)) { Fail 'Docker is not installed. Install Docker Desktop (https://www.docker.com/products/docker-desktop/) and start it.' }
    docker info *> $null
    if ($LASTEXITCODE -ne 0) { Fail 'Docker is installed but not running. Start Docker Desktop, wait until it says "Engine running", then try again.' }
}

function New-Secret([int]$length) {
    $chars = 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789'.ToCharArray()
    $bytes = New-Object byte[] ($length * 2)
    $rng = New-Object System.Security.Cryptography.RNGCryptoServiceProvider
    $rng.GetBytes($bytes); $rng.Dispose()
    $out = New-Object System.Text.StringBuilder
    $limit = 256 - (256 % $chars.Length)   # discard bytes above the last full multiple of the alphabet size: no modulo bias
    foreach ($b in $bytes) { if ($out.Length -lt $length -and $b -lt $limit) { [void]$out.Append($chars[$b % $chars.Length]) } }
    return $out.ToString()
}

function Get-LanIp {
    try {
        $cfg = Get-NetIPConfiguration | Where-Object { $_.IPv4DefaultGateway -and $_.IPv4Address } | Select-Object -First 1
        if ($cfg) { return $cfg.IPv4Address[0].IPAddress }
    } catch { }
    return 'localhost'
}

function Read-EnvFile {
    if (-not (Test-Path $EnvFile)) { Fail 'No .env yet. Run: setup' }
    $map = @{}
    foreach ($line in Get-Content $EnvFile) {
        if ($line -match '^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$') { $map[$Matches[1]] = $Matches[2].Trim() }
    }
    return $map
}

function Show-Urls($cfg) {
    $api = if ($cfg['API_PORT']) { $cfg['API_PORT'] } else { '8080' }
    $nats = if ($cfg['NATS_PORT']) { $cfg['NATS_PORT'] } else { '4222' }
    Write-Host ''
    Write-Host "Dashboard : http://localhost:$api/   (agents use $($cfg['PUBLIC_URL']))" -ForegroundColor Green
    Write-Host "NATS port : $nats   (endpoints must reach this computer on $api and $nats; run 'firewall' as Administrator)" -ForegroundColor Green
}

switch ($Command) {
    'help' { Get-Help $PSCommandPath | Out-String | Write-Host }

    'setup' {
        if (Test-Path $EnvFile) { Fail '.env already exists. Delete it first if you really want new secrets (the database keeps the old password).' }
        $url = if ($PublicUrl) { $PublicUrl.TrimEnd('/') } else { 'http://' + (Get-LanIp) + ':8080' }
        $admin = New-Secret 16
        $text = @(
            '# Generated by nettactical.ps1 setup. Never commit this file.',
            "POSTGRES_PASSWORD=$(New-Secret 24)",
            "TACTICAL_SECRET_KEY=$(New-Secret 48)",
            'ADMIN_USERNAME=admin',
            "ADMIN_PASSWORD=$admin",
            "PUBLIC_URL=$url",
            'API_PORT=8080',
            'NATS_PORT=4222'
        ) -join "`n"
        [System.IO.File]::WriteAllText($EnvFile, $text + "`n", (New-Object System.Text.UTF8Encoding($false)))   # no BOM: a BOM breaks the first variable
        Write-Host '.env created.' -ForegroundColor Green
        Write-Host "First admin login:  admin / $admin   (shown once here; it is also stored in .env)" -ForegroundColor Yellow
        Write-Host "PUBLIC_URL is $url . Change it in .env if agents reach this computer under another address (then run: up)."
        Write-Host 'Next: .\scripts\windows\nettactical.cmd up'
    }

    'up' {
        Test-Docker
        $cfg = Read-EnvFile
        foreach ($k in 'POSTGRES_PASSWORD', 'TACTICAL_SECRET_KEY', 'ADMIN_PASSWORD') { if (-not $cfg[$k]) { Fail "$k is empty in .env" } }
        Info 'Building and starting (the first run downloads images and can take several minutes)...'
        docker compose up -d --build
        if ($LASTEXITCODE -ne 0) { Fail 'docker compose failed. See the messages above.' }
        $port = if ($cfg['API_PORT']) { $cfg['API_PORT'] } else { '8080' }
        Info 'Waiting for the dashboard...'
        $ok = $false
        for ($i = 0; $i -lt 45 -and -not $ok; $i++) {
            try { $r = Invoke-WebRequest -Uri "http://localhost:$port/" -UseBasicParsing -TimeoutSec 3; $ok = ($r.StatusCode -eq 200) } catch { Start-Sleep -Seconds 2 }
        }
        if ($ok) { Show-Urls $cfg } else { Write-Host "The dashboard did not answer yet. Check: .\scripts\windows\nettactical.cmd logs api" -ForegroundColor Yellow }
    }

    'down' { Test-Docker; docker compose down }

    'status' {
        Test-Docker
        $cfg = Read-EnvFile
        docker compose ps
        foreach ($p in @(@('API', $(if ($cfg['API_PORT']) { $cfg['API_PORT'] } else { '8080' })), @('NATS', $(if ($cfg['NATS_PORT']) { $cfg['NATS_PORT'] } else { '4222' })))) {
            $t = Test-NetConnection -ComputerName 127.0.0.1 -Port ([int]$p[1]) -WarningAction SilentlyContinue
            $state = if ($t.TcpTestSucceeded) { 'reachable' } else { 'NOT reachable' }
            Write-Host ("{0,-5} port {1}: {2}" -f $p[0], $p[1], $state) -ForegroundColor $(if ($t.TcpTestSucceeded) { 'Green' } else { 'Red' })
        }
    }

    'logs' {
        Test-Docker
        if ($Arg) { docker compose logs -f --tail 100 $Arg } else { docker compose logs -f --tail 100 }
    }

    'update' {
        Test-Docker
        if (Test-Path (Join-Path $Root '.git')) {
            if (Get-Command git -ErrorAction SilentlyContinue) { git pull } else { Fail 'git is not installed. Update the files by hand, then run: up' }
        } else { Write-Host 'Not a git checkout: copy the new files over this folder first (keep .env).' -ForegroundColor Yellow }
        docker compose up -d --build
    }

    'firewall' {
        $admin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
        if (-not $admin) { Fail 'Run this command from a PowerShell or Command Prompt opened as Administrator.' }
        $cfg = Read-EnvFile
        $api = if ($cfg['API_PORT']) { $cfg['API_PORT'] } else { '8080' }
        $nats = if ($cfg['NATS_PORT']) { $cfg['NATS_PORT'] } else { '4222' }
        foreach ($n in 'NetTactical API', 'NetTactical NATS') { Get-NetFirewallRule -DisplayName $n -ErrorAction SilentlyContinue | Remove-NetFirewallRule }
        # Private and Domain networks only: never open these on a Public (cafe, hotel) network.
        New-NetFirewallRule -DisplayName 'NetTactical API' -Direction Inbound -Action Allow -Protocol TCP -LocalPort $api -Profile Private, Domain | Out-Null
        New-NetFirewallRule -DisplayName 'NetTactical NATS' -Direction Inbound -Action Allow -Protocol TCP -LocalPort $nats -Profile Private, Domain | Out-Null
        Write-Host "Opened TCP $api and $nats for Private and Domain networks. If your network is marked Public, change it to Private in Windows settings." -ForegroundColor Green
    }

    'backup' {
        Test-Docker
        New-Item -ItemType Directory -Force -Path (Join-Path $Root 'backups') | Out-Null
        $name = 'tacticalrmm-' + (Get-Date -Format 'yyyyMMdd-HHmmss') + '.dump'
        docker compose exec -T db pg_dump -U tactical -Fc -f "/tmp/$name" tacticalrmm
        if ($LASTEXITCODE -ne 0) { Fail 'pg_dump failed. Is the stack running? (status)' }
        docker compose cp "db:/tmp/$name" (Join-Path $Root "backups\$name")
        docker compose exec -T db rm -f "/tmp/$name"
        Write-Host "Backup saved: backups\$name" -ForegroundColor Green
        Write-Host "Restore (replaces current data): docker compose cp backups\$name db:/tmp/restore.dump ; docker compose exec -T db pg_restore -U tactical -d tacticalrmm --clean --if-exists /tmp/restore.dump"
    }
}
